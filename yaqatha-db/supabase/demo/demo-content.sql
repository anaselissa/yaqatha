create function pg_temp.mat(p_slug text, p_title text, p_desc text, p_type text, p_body text, p_url text,
  p_src_title text, p_src_url text, p_author text, p_nature text, p_needs text[], p_domain text) returns uuid
language plpgsql as $$
declare mid uuid;
begin
  insert into public.materials (slug, title, description, type, body, url, source_title, source_url, author, nature)
  values (p_slug, '[تجريبي] ' || p_title, p_desc, p_type::public.material_type, p_body, p_url, p_src_title, p_src_url, p_author, p_nature::public.content_nature)
  returning id into mid;
  insert into public.material_needs (material_id, need_id) select mid, id from public.needs where slug = any(p_needs);
  insert into public.material_domains (material_id, domain_id) select mid, id from public.domains where slug = p_domain;
  update public.materials set status = 'published' where id = mid;
  return mid;
end $$;

create function pg_temp.vid(p_slug text, p_title text, p_desc text, p_yt text, p_needs text[], p_domain text) returns uuid
language sql as $$
  select pg_temp.mat(p_slug, p_title, p_desc, 'video', null, 'https://www.youtube.com/watch?v=' || p_yt,
