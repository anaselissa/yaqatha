$$;

create function pg_temp.q(p_mat text, p_pos int, p_prompt text, p_opts jsonb, p_correct int, p_expl text) returns void
language sql as $$
  insert into public.material_questions (material_id, position, prompt, options, correct_index, explanation)
  select id, p_pos, p_prompt, p_opts, p_correct, p_expl from public.materials where slug = p_mat
$$;

create function pg_temp.path(p_slug text, p_title text, p_desc text, p_purpose text, p_days int, p_ct text, p_needs text[], p_domain text) returns void
language plpgsql as $$
declare pid uuid;
begin
  insert into public.paths (slug, change_type) values (p_slug, p_ct::public.change_type) returning id into pid;
  insert into public.path_versions (path_id, title, description, purpose, duration_days)
  values (pid, '[تجريبي] ' || p_title, p_desc, p_purpose, p_days);
  insert into public.path_needs (path_id, need_id) select pid, id from public.needs where slug = any(p_needs);
  insert into public.path_domains (path_id, domain_id) select pid, id from public.domains where slug = p_domain;
end $$;

create function pg_temp.step(p_path text, p_pos int, p_type text, p_title text, p_ins text, p_mats text[] default '{}') returns void
language plpgsql as $$
declare sid uuid;
begin
  insert into public.steps (version_id, position, type, title, instructions)
  select v.id, p_pos, p_type::public.step_type, p_title, p_ins
  from public.path_versions v join public.paths p on p.id = v.path_id where p.slug = p_path
  returning id into sid;
  insert into public.step_materials (step_id, material_id, position)
  select sid, m.id, x.ord from unnest(p_mats) with ordinality as x(slug, ord) join public.materials m on m.slug = x.slug;
end $$;

create function pg_temp.goal(p_path text, p_pos int, p_title text, p_desc text) returns void
language sql as $$
  insert into public.path_suggested_goals (path_id, position, title, description)
  select id, p_pos, p_title, p_desc from public.paths where slug = p_path
$$;

create function pg_temp.next(p_path text, p_next text, p_pos int) returns void
language sql as $$
  insert into public.path_next (path_id, next_path_id, position)
  select a.id, b.id, p_pos from public.paths a, public.paths b where a.slug = p_path and b.slug = p_next
$$;

